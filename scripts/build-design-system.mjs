import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

// Ship the official Tabler native control rules, without its page scaffolding
// or global reboot. Declarations are copied verbatim, not reimplemented.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = path.join(root, 'node_modules/@tabler/core');
const source = postcss.parse(await readFile(path.join(packageRoot, 'dist/css/tabler.css'), 'utf8'));
const component = /\.(?:btn(?:[\w-]*)?|form-[\w-]+|input-group[\w-]*|badge[\w-]*|alert[\w-]*|spinner-[\w-]+|invalid-feedback|valid-feedback)(?![\w-])/;
const output = postcss.root();
function retain(node) {
  if (node.type === 'rule') {
    if (node.selector.includes(':root') || node.selector.includes('[data-bs-theme=')) return node.clone();
    const selectors = node.selectors.filter(selector => component.test(selector));
    return selectors.length ? node.clone({ selector: selectors.join(',\n') }) : null;
  }
  if (node.type === 'atrule' && node.name === 'keyframes' && /spinner/.test(node.params)) return node.clone();
  if (node.type === 'atrule' && ['media', 'supports'].includes(node.name)) {
    const group = node.clone({ nodes: [] });
    node.each(child => { const kept = retain(child); if (kept) group.append(kept); });
    return group.nodes.length ? group : null;
  }
  return null;
}
source.each(node => { const kept = retain(node); if (kept) output.append(kept); });
const dest = path.join(root, 'public/vendor/tabler');
await mkdir(dest, { recursive: true });
// The npm package omits its root LICENSE. Keep the upstream MIT license
// vendored alongside the generated CSS (see NOTICE.md for provenance).
await readFile(path.join(dest, 'LICENSE'), 'utf8');
await writeFile(path.join(dest, 'controls.css'), '/*! Tabler Core 1.5.0 | Copyright 2018-2026 The Tabler Authors, codecalm.net Pawel Kuna | MIT | https://tabler.io | Generated by npm run build:design */\n' + output.toString() + '\n');
console.log(`Tabler control styles built: ${output.nodes.length} rule groups`);
